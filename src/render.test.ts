import { describe, expect, it } from "vitest";
import { DEFAULT_OPTIONS, LANGUAGES, type ProjectOptions } from "./config.ts";
import { render, type RenderInput } from "./render.ts";

/** The paragraph that opens "Committing". */
const NO_COMMIT_ALL = "Never `git commit -a` because there may be others working; stage changes manually.\n\n";

/** The languages that have classes, for which the template advises on when to use them. */
const CLASS_LANGUAGES: ReadonlySet<string> = new Set(["typescript", "javascript", "svelte", "python", "cpp", "csharp"]);

const BASE: RenderInput = { options_text: "", options: DEFAULT_OPTIONS, project_sections: [], web_design_body: "" };

/** @returns The rendered file for the defaults overridden by `patch`. */
function render_with(patch: Partial<ProjectOptions>, input: Partial<RenderInput> = {}): Promise<string> {
	return render({ ...BASE, ...input, options: { ...DEFAULT_OPTIONS, ...patch } });
}

describe("render", () => {
	it("starts with the header, carrying the options text, then the hostname check", async () => {
		const text = await render_with({}, { options_text: "\nlanguages = [\"rust\"]\n" });
		expect(text.startsWith("<!-- clank-right\n# This file is generated by `clank-right`")).toBe(true);
		expect(text).toContain("run `clank-right update .` in this repo");
		expect(text).toContain("\n\nlanguages = [\"rust\"]\n-->\n\n# Before starting\n\nWelcome. Before starting or resuming work, check what `hostname` outputs.\n");
	});

	it("omits Node and Python material for a project in neither", async () => {
		const text = await render_with({ languages: ["rust"] });
		expect(text).not.toContain("# Working with Node projects");
		expect(text).not.toContain("# Working with Python projects");
		expect(text).not.toContain("# Libraries to use");
		expect(text).toContain("\nWhen writing _any_ kind of code:\n\n- Think about invariants");
		expect(text).toContain("Minutae:\n\n- Blank lines inside functions");
		expect(text).not.toContain("For CREATE TABLE");
	});

	it("includes Node material for a TypeScript project", async () => {
		const text = await render_with({ languages: ["typescript"] });
		expect(text).toContain("# Working with Node projects\n\nnpm sux");
		expect(text).toContain("When writing _any_ kind of code, including for the above:");
		expect(text).toContain("Minutae:\n\n- Use the { } curlies even for one-statement blocks.\n- Block contents");
		expect(text).toContain("`break`, `throw`, `yield`, `await` statements");
		expect(text).toContain("# Libraries to use\n\n- `ayy`");
		expect(text).not.toContain("`effection`");
	});

	it("tells agents to use bun, not pnpm, in a bun project", async () => {
		const text = await render_with({ languages: ["typescript"], package_manager: "bun" });
		expect(text).toContain("# Working with Node projects\n\nThis project uses bun; avoid running npm or pnpm.\n\n# There's plenty of time");
		expect(text).not.toContain("npm sux");
		expect(text).toContain(", pnpm, bun, oxfmt, ");
		expect(await render_with({ languages: ["typescript"] })).toContain(", pnpm, oxfmt, ");
	});

	it("adds effection and extra libraries when asked", async () => {
		const text = await render_with({ languages: ["svelte"], effection: true, libraries_extra: ["`ventojs` for templating.", "`ws` for sockets."] });
		expect(text).toContain("when observing the system.\n- `effection`. We like structured programming");
		expect(text).toContain("(unless needed).\n- `vitest` for unit tests");
		expect(text).toContain("string or number.\n- `ventojs` for templating.\n- `ws` for sockets.\n\n# Thoughts for when");
	});

	it("adds the Python material, indented with spaces unless asked for tabs", async () => {
		const text = await render_with({ languages: ["python"] });
		expect(text).toContain("# Working with Python projects\n\nPrefer `uv` and `uvx` over pip.");
		expect(text).not.toContain("# Working with Node projects");
		expect(text).toContain("# Code conventions\n\nFor Python code:\n\n- Use 4 spaces to indent and spaces to align.\n");
		expect(text).toContain("When writing _any_ kind of code, including for the above:");
		expect(text).toContain("Minutae:\n\n- Block contents should not be on the same line that opened the block.\n- Put `return`, `continue`, `break`, `raise`, `yield`, `await` statements");
		expect(text).toContain("# Libraries to use\n\n- `logging` from the standard library");
		expect(text).not.toContain("`ayy`");
		const tabs = await render_with({ languages: ["python"], python_indent: "tabs" });
		expect(tabs).toContain("\nFor Python code:\n\n- Use tabs to indent and spaces to align.\n");
	});

	it("lists the extra libraries for a project in neither Node nor Python, and no section without them", async () => {
		const text = await render_with({ languages: ["rust"], libraries_extra: ["`tokio` for async."] });
		expect(text).toContain("# Libraries to use\n\n- `tokio` for async.\n\n# Thoughts for when");
		expect(await render_with({ languages: ["rust"] })).not.toContain("# Libraries to use");
	});

	it("lists the Node libraries, then the Python ones, then the extras in a mixed project", async () => {
		const text = await render_with({ languages: ["typescript", "python"], libraries_extra: ["`ws` for sockets."] });
		expect(text).toContain("# Working with Node projects\n\nnpm sux");
		expect(text).toContain("# Working with Python projects");
		expect(text).toContain("For JavaScript, TypeScript, and Svelte-related code:");
		expect(text).toContain("no ASI.\n\nFor Python code:");
		expect(text).toContain("Minutae:\n\n- Use the { } curlies even for one-statement blocks.\n- Block contents");
		expect(text).toContain("`break`, `throw`, `raise`, `yield`, `await` statements");
		expect(text).toContain("string or number.\n- `logging` from the standard library");
		expect(text).toContain("string or number.\n- `ws` for sockets.\n\n# Thoughts for when");
	});

	it.each(["c", "cpp", "csharp"] as const)("adds the brace rules for %s without the Node material", async (language) => {
		const text = await render_with({ languages: [language] });
		expect(text).toContain("\nWhen writing _any_ kind of code:\n\n- Think about invariants");
		expect(text).toContain("Minutae:\n\n- Use the { } curlies even for one-statement blocks.\n- Block contents");
		expect(text).toContain("`break`, `throw`, `yield`, `await` statements");
		expect(text).not.toContain("# Working with Node projects");
		expect(text).not.toContain("# Libraries to use");
	});

	it.each(LANGUAGES)("advises on classes only if %s has them", async (language) => {
		const text = await render_with({ languages: [language] });
		const has_classes = CLASS_LANGUAGES.has(language);
		expect(text.includes("avoid talking about other things.\n- Classes should be used when:")).toBe(has_classes);
		expect(text).toContain((has_classes ? "plain functions are generally fine." : "avoid talking about other things.") + "\n\nMinutae:");
	});

	it("adds the DDL paragraph for SQL", async () => {
		const text = await render_with({ languages: ["sql"] });
		expect(text).toContain("User loves AskUserQuestion.\n\nFor CREATE TABLE i.e. DDL work");
	});

	it("puts the sandbox note in the hostname bullet and extra tools after uv", async () => {
		const text = await render_with({ sandbox_note: "you're unable to hit production", tools_extra: ["ffmpeg", "nm"] });
		expect(text).toContain("- If it ends in \"clank\", you're unable to hit production; run whatever commands you need.\n- Otherwise, stop");
		expect(text).toContain(", uv, ffmpeg, nm, psql, ");
		expect(await render_with({})).toContain("- If it ends in \"clank\", run whatever commands you need.");
	});

	it("renders the web design variants", async () => {
		expect(await render_with({})).not.toContain("# Web design");
		const dark = await render_with({ web_design: "2010", color_scheme: "dark" });
		expect(dark).toContain("# Web design\n\nSet your mind to 2010 styling");
		expect(dark).toContain("native HTML elements.\n\nThis is a \"dark mode\"-only project");
		expect(await render_with({ web_design: "2010", color_scheme: "light" })).toContain("\"light mode\"-only project");
		expect(await render_with({ web_design: "2010" })).toContain("native HTML elements.\n\nPlease keep things working well in both light mode and dark mode.\n\nWrite CSS");
		const custom = await render_with({ web_design: "custom" }, { web_design_body: "Bespoke.\n\n- rules" });
		expect(custom).toContain("# Web design\n\nBespoke.\n\n- rules\n\n# Thoughts for when there is programming involved");
		expect(custom).not.toContain("2010 styling");
	});

	it("follows the last project section with Committing: the no-commit-all paragraph, then the commit template", async () => {
		const text = await render_with({}, { project_sections: [{ heading: "Before committing", body: "\tcargo test" }] });
		expect(text).toContain("# Before committing\n\n\tcargo test\n\n# Committing\n\n" + NO_COMMIT_ALL + "Automatically commit your changes with this commit template:\n\n\tsubsystem:");
		expect(text).not.toContain("After making changes");
	});

	it("replaces the commit template for nixpkgs-style commits", async () => {
		const text = await render_with({ commit_style: "nixpkgs" });
		expect(text).toContain("# Committing\n\n" + NO_COMMIT_ALL + "Automatically commit your changes as per the standard nixpkgs style for doing commits. Check the git log for a particular directory if uncertain.\n\n# Code review after each commit");
		expect(text).not.toContain("<prompt>");
	});

	it("leaves out our conventions and libraries for a fork that follows upstream's, but not the project's additions", async () => {
		const text = await render_with({ languages: ["typescript", "python"], conventions: "upstream", effection: true });
		expect(text).toContain("# Working with Node projects\n\nnpm sux");
		expect(text).toContain("keep existing lines.\n\n# Thoughts for when there is programming involved");
		expect(text).not.toContain("# Code conventions");
		expect(text).not.toContain("# Libraries to use");
		const added = await render_with({ languages: ["typescript", "python"], conventions: "upstream", libraries_extra: ["`ws` for sockets."] });
		expect(added).toContain("keep existing lines.\n\n# Libraries to use\n\n- `ws` for sockets.\n\n# Thoughts for when");
	});

	it("places project sections between Thoughts for when there is programming involved and Committing, verbatim", async () => {
		const sections = [{ heading: "Project map", body: "- a/\n- b/" }, { heading: "The app", body: "Text.\n\n\n\n```\n\n\n# code\n```" }];
		const text = await render_with({}, { project_sections: sections });
		expect(text).toContain("User loves AskUserQuestion.\n\n# Project map\n\n- a/\n- b/\n\n# The app\n\nText.\n\n\n\n```\n\n\n# code\n```\n\n# Committing\n");
	});

	it("carries the options text through verbatim, blank lines included", async () => {
		const options_text = "languages = [\"rust\"]\n\n\n# an S3 server\ntools_extra = [\n\t\"garage\",\n]";
		const text = await render_with({}, { options_text });
		expect(text).toContain(`is overwritten.\n\n${options_text}\n-->\n\n# Before starting\n`);
	});

	it("never leaves runs of blank lines and ends with one newline", async () => {
		const upstream: Partial<ProjectOptions> = { languages: ["typescript"], conventions: "upstream", libraries_extra: ["`ws` for sockets."] };
		for (const text of [await render_with({}), await render_with({ languages: ["typescript", "c", "sql"], web_design: "2010" }), await render_with(upstream)]) {
			expect(text).not.toMatch(/\n{3,}/);
			expect(text.endsWith("\n")).toBe(true);
			expect(text.endsWith("\n\n")).toBe(false);
		}
	});
});
